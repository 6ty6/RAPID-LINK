import { test, expect } from '@playwright/test'

test('test application validates, retains edits and never submits', async ({ page }) => {
 let sent=0
 page.on('request',request=>{if(request.method()==='POST')sent++})
 await page.goto('/open-account?preview=true')
 await expect(page.getByText('Test form — submissions are disabled')).toBeVisible()
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await expect(page.getByRole('heading',{name:'1. Account',exact:true})).toBeVisible()
 await page.getByRole('radio',{name:'Savings account',exact:true}).check()
 await page.getByRole('radio',{name:'Madina',exact:true}).check()
 await page.getByRole('radio',{name:'Asylum Down',exact:true}).check()
 await page.getByRole('radio',{name:'Madina',exact:true}).check()
 await expect(page.getByRole('radio',{name:'Asylum Down',exact:true})).not.toBeChecked()
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByLabel('Title',{exact:false}).selectOption('Miss')
 await page.getByLabel('First and middle').fill('Test Esi')
 await page.getByLabel('Surname (as').fill('Example')
 await page.getByLabel('Gender').selectOption('female')
 await page.getByLabel('Date of birth').fill('1990-03-15')
 await page.getByLabel('Phone number,').fill('0200000000')
 await page.getByLabel('Ghana Card number:').fill('GHA-123456789-0')
 await page.getByLabel('Ghana Card issue date').fill('2021-06-12')
 await page.getByLabel('Ghana Card expiry date').fill('2022-06-12')
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('expired')
 await page.getByLabel('Ghana Card expiry date').fill('2035-06-12')
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByLabel('Residential address').fill('Test address only')
 await page.getByLabel('Occupation').fill('Trader')
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await page.getByRole('button',{name:'Review application'}).click()
 await expect(page.getByText('Please add your passport-style photograph.')).toBeVisible()
 const png=Buffer.from(await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=32;canvas.height=32;canvas.getContext('2d').fillRect(0,0,32,32);return canvas.toDataURL('image/png').split(',')[1]}),'base64')
 await page.locator('#photo').setInputFiles({name:'sample.png',mimeType:'image/png',buffer:png})
 await page.locator('#signature').setInputFiles({name:'signature.png',mimeType:'image/png',buffer:png})
 await expect(page.getByAltText('Passport-style photograph preview')).toBeVisible()
 await expect(page.getByAltText('Signature photo or scan preview')).toBeVisible()
 await page.getByRole('button',{name:'Review application'}).click()
 await expect(page.getByRole('heading',{name:'5. Review',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Submission unavailable in this test'})).toBeDisabled()
 await page.getByRole('button',{name:'Edit your details'}).click()
 await expect(page.getByLabel('First and middle')).toHaveValue('Test Esi')
 let dialogs=0
 page.on('dialog',async dialog=>{dialogs++;await dialog.dismiss()})
 await page.getByRole('button',{name:'Clear form',exact:true}).click()
 await expect(page.getByRole('button',{name:'Keep my entries'})).toBeFocused()
 await page.getByRole('button',{name:'Keep my entries'}).click()
 await expect(page.getByLabel('First and middle')).toHaveValue('Test Esi')
 await page.getByRole('button',{name:'Clear form',exact:true}).click()
 await page.keyboard.press('Escape')
 await expect(page.getByRole('button',{name:'Clear form',exact:true})).toBeFocused()
 await page.getByRole('button',{name:'Clear form',exact:true}).click()
 await page.getByRole('button',{name:'Yes, clear form',exact:true}).click()
 await expect(page.getByRole('heading',{name:'1. Account',exact:true})).toBeVisible()
 await expect(page.getByRole('radio',{name:'Savings account',exact:true})).not.toBeChecked()
 expect(dialogs).toBe(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(sent).toBe(0)
 await page.reload()
 await page.getByRole('radio',{name:'Savings account',exact:true}).check()
 await page.getByRole('button',{name:'Continue',exact:true}).click()
 await expect(page.getByLabel('First and middle')).toHaveValue('')
})

