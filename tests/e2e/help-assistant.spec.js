test('suggestions step aside during typing, return after inactivity and new chat clears messages', async ({ page }) => {
  await page.clock.install()
  await page.goto('/home')
  await page.getByRole('button', { name: 'Open Abena', exact: true }).click()
  const panel = page.getByRole('dialog', { name: 'Abena', exact: true })
  await panel.getByLabel('Message Abena').fill('Hello')
  await expect(panel.getByRole('group', { name: 'Suggested questions' })).toHaveCount(0)
  await page.clock.fastForward(12000)
  await expect(panel.getByRole('group', { name: 'Suggested questions' })).toBeVisible()
  await expect(panel.getByLabel('Message Abena')).toHaveValue('Hello')
  await panel.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(panel.getByRole('status')).toBeVisible()
  await page.clock.fastForward(2200)
  await expect(panel.locator('.message-user')).toHaveCount(1)
  await expect(panel.locator('.message-assistant')).toHaveCount(2)
  await panel.getByRole('button', { name: 'New chat' }).click()
  await expect(panel.locator('.message-user')).toHaveCount(0)
  await expect(panel.locator('.message-assistant')).toHaveCount(1)
  await expect(panel.getByLabel('Message Abena')).toBeFocused()
})

