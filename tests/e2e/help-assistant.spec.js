import { test, expect } from '@playwright/test'

test('assistant replies conversationally to quick questions and typed messages', async ({ page }) => {
  await page.clock.install()
  await page.goto('/home')
  const launch = page.getByRole('button', { name: 'Open Abena', exact: true })
  await launch.click()
  const panel = page.getByRole('dialog', { name: 'Abena', exact: true })
  await expect(panel).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Close Abena' })).toBeFocused()
  await panel.getByRole('button', { name: 'Open an account', exact: true }).click()
  await expect(panel.getByRole('log')).toContainText('How can I open an account?')
  await expect(panel.getByRole('status')).toContainText('preparing a reply')
  await expect(panel.getByRole('group', { name: 'Suggested questions' })).toHaveCount(0)
  await page.clock.fastForward(2200)
  await expect(panel.getByRole('log')).toContainText('Online account opening is coming soon')
  await panel.getByLabel('Message Abena').fill('Where are your branches?')
  await panel.getByRole('button', { name: 'Send', exact: true }).click()
  await page.clock.fastForward(2200)
  await expect(panel.getByRole('log')).toContainText('Asylum Down')
  await expect(panel.getByRole('log')).toContainText('How can I open an account?')
  await panel.getByRole('link', { name: 'Find our branches' }).click()
  await expect(page).toHaveURL(/contact#branch-map-title$/)
  await expect(panel).toHaveCount(0)
  await launch.click()
  await expect(panel.getByRole('log')).toContainText('Where are your branches?')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Open Abena', exact: true })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('assistant can be hidden and restored and stays off staff routes', async ({ page }) => {
  await page.goto('/home')
  await page.getByRole('button', { name: 'Hide Abena' }).click()
  const restore = page.getByRole('button', { name: 'Show Abena' })
  await expect(restore).toBeVisible()
  await page.reload()
  await expect(restore).toBeVisible()
  await restore.click()
  await expect(page.getByRole('button', { name: 'Open Abena' })).toBeVisible()
  await page.goto('/accept-invite')
  await expect(page.locator('.rapidlink-help, .help-restore')).toHaveCount(0)
})

test('idle expressions settle down and reduced-motion stops animations', async ({ page }) => {
  await page.clock.install()
  await page.goto('/home')
  const character = page.locator('.help-character-dock .help-character')
  await expect(character).toHaveClass(/pose-peek/)
  await page.clock.fastForward(1800)
  await expect(character).toHaveClass(/pose-playing/)
  await page.clock.fastForward(24000)
  await expect(character).toHaveClass(/pose-sulking/)
  await page.clock.fastForward(800)
  await expect(character).toHaveClass(/pose-sulky/)
  await page.clock.fastForward(4500)
  await expect(character).toHaveClass(/pose-settling/)
  await page.clock.fastForward(900)
  await expect(character).toHaveClass(/pose-resting/)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.character-body')).toHaveCSS('animation-name', 'none')
})

test('outside clicks close Abena while inside clicks stay open and hide does not cover text', async ({ page }) => {
  await page.goto('/home')
  const hide = await page.getByRole('button', { name: 'Hide Abena' }).boundingBox()
  const greeting = await page.locator('.help-character-label').boundingBox()
  const overlaps = hide.x < greeting.x + greeting.width && hide.x + hide.width > greeting.x && hide.y < greeting.y + greeting.height && hide.y + hide.height > greeting.y
  expect(overlaps).toBe(false)
  await page.getByRole('button', { name: 'Open Abena', exact: true }).click()
  const panel = page.getByRole('dialog', { name: 'Abena', exact: true })
  await panel.getByRole('button', { name: 'Common questions', exact: true }).click()
  await expect(panel).toBeVisible()
  await page.mouse.click(5, 100)
  await expect(panel).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Open Abena', exact: true })).toBeVisible()
})

test('Abena header and close control stay above navigation in a short viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 520 })
  await page.goto('/home')
  const menuToggle = page.locator('.menu-toggle')
  if (await menuToggle.isVisible()) await menuToggle.click()
  await page.getByRole('button', { name: 'Open Abena', exact: true }).click()
  const panel = page.getByRole('dialog', { name: 'Abena', exact: true })
  const close = panel.getByRole('button', { name: 'Close Abena', exact: true })
  await expect(close).toBeInViewport()
  const unobstructed = await close.evaluate(button => {
    const box = button.getBoundingClientRect()
    return button.contains(document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2))
  })
  expect(unobstructed).toBe(true)
  await panel.locator('.help-panel-body').evaluate(body => { body.scrollTop = body.scrollHeight })
  await expect(close).toBeInViewport()
  await close.click()
  await expect(panel).toHaveCount(0)
})

