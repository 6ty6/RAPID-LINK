import { test, expect } from '@playwright/test'
async function openSection(page, name) {
  const toggle = page.getByRole('button', {name:'Browse sections',exact:true})
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click()
  await page.getByRole('button', {name}).click()
}


test('writer drafts, separate approver publishes, public page updates and withdrawn content disappears', async ({ page, request }, testInfo) => {
  const title = `Synthetic CMS question ${testInfo.project.name} ${Date.now()}`
  const answer = 'This is a synthetic test answer, created only in the local demonstration.'
  await page.goto('/cms')
  await page.getByRole('button', { name: 'Demo writer', exact: false }).click()
  await openSection(page, /^FAQs/)
  await page.getByRole('button', { name: 'Create faqs' }).click()
  await page.getByLabel('Title *', { exact: true }).fill(title)
  await expect(page.getByLabel('URL slug *', { exact: true })).toHaveValue(title.toLowerCase().replaceAll(' ', '-'))
  await page.getByLabel('Answer *', { exact: true }).fill(answer)
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status').filter({hasText:'Draft saved'})).toBeVisible()
  await page.getByRole('button', { name: 'Submit for review', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Approve', exact: true })).toHaveCount(0)
  let records = (await (await request.get('http://127.0.0.1:8791/api/cms/public')).json()).records
  expect(records.some(record => record.title === title)).toBeFalsy()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByRole('button', { name: 'Demo approver', exact: false }).click()
  await openSection(page, /^FAQs/)
  await page.getByRole('button', { name: title, exact: false }).click()
  await page.getByRole('button', { name: 'Approve', exact: true }).click()
  await page.getByRole('button', { name: 'Publish approved version', exact: true }).click()
  await expect(page.getByRole('status').filter({hasText:'Published public version updated'})).toBeVisible()
  await page.screenshot({path:`.cms-data/cms-${testInfo.project.name}.png`,fullPage:true})
  const publicPage = await page.context().newPage()
  await publicPage.goto('/faqs')
  await publicPage.getByText(title, {exact:true}).click()
  await expect(publicPage.getByText(answer,{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Unpublish',exact:true}).click()
  await publicPage.reload()
  await expect(publicPage.getByText(title,{exact:true})).toHaveCount(0)
  await publicPage.close()
})

test('staff workspace fits the viewport and private admin functions are absent for writers', async ({ page }, testInfo) => {
  await page.goto('/cms')
  await page.getByRole('button',{name:'Demo writer',exact:false}).click()
  await expect(page.getByRole('button',{name:'Staff access',exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Export content',exact:true})).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'Content workspace'})).toBeVisible()
  await expect(page.locator('.cms-nav')).toHaveCSS('background-color', 'rgb(16, 44, 70)')
  for (const name of ['Website & homepage', 'News & careers', 'Company information', 'Customer help']) await expect(page.getByRole('heading',{name,level:3,exact:true})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
  await page.screenshot({path:'.cms-data/overview-'+testInfo.project.name+'.png', fullPage:true})
  await page.getByRole('button',{name:'Manage FAQs',exact:true}).click()
  await page.getByRole('button',{name:'Create faqs',exact:true}).click()
  await expect(page.locator('.cms-records')).toHaveCount(0)
  await expect(page.getByRole('list',{name:'Publishing steps'})).toBeVisible()
  await page.getByRole('button',{name:'Back to faqs',exact:true}).click()
  await expect(page.getByRole('button',{name:'Create faqs',exact:true})).toBeVisible()
})

test('administrator imports existing content as drafts without publishing it', async ({ page, request }) => {
  const before=(await (await request.get('http://127.0.0.1:8791/api/cms/public')).json()).records
  await page.goto('/cms')
  await page.getByRole('button',{name:'Demo administrator',exact:false}).click()
  await openSection(page, 'Import & export')
  await page.getByRole('button',{name:'Import existing content as drafts',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'Nothing was published.'})).toBeVisible()
  const after=(await (await request.get('http://127.0.0.1:8791/api/cms/public')).json()).records
  expect(after).toEqual(before)
  await openSection(page, /^News/)
  await page.getByRole('button',{name:/Bank of Ghana revises sanctions/}).click()
  await expect(page.getByLabel('Category *',{exact:true})).toHaveValue('Customer Notices')
  await expect(page.getByRole('button',{name:'Submit for review',exact:true})).toBeVisible()
})

test('CMS-published replies reach Abena, while drafts and withdrawn replies stay unavailable', async ({ page, request }, testInfo) => {
  const unique = `${testInfo.project.name} ${Date.now().toString(36).replace(/[0-9]/g, digit => String.fromCharCode(97 + Number(digit)))}`
  const question = `Where can I find the preview notice ${unique}?`
  const approved = `This is the approved preview answer ${unique}.`
  await page.goto('/cms')
  await expect(page.getByRole('button',{name:'Open Abena',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Demo writer',exact:false}).click()
  await openSection(page,/^Abena answers/)
  await page.getByRole('button',{name:'Create abena answers',exact:true}).click()
  await page.getByLabel('Title *',{exact:true}).fill(`Preview answer ${unique}`)
  await page.getByLabel('Example questions',{exact:true}).fill(question)
  await page.getByLabel('Prepared reply variations *',{exact:true}).fill(approved)
  await page.getByLabel('Approved information source *',{exact:true}).fill('Synthetic integration test')
  await page.getByRole('button',{name:'Save draft',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'Draft saved'})).toBeVisible()
  const publicPage=await page.context().newPage()
  async function ask() {
    await publicPage.goto('/')
    await publicPage.getByRole('button',{name:'Open Abena',exact:true}).click()
    await publicPage.getByLabel('Message Abena',{exact:true}).fill(question)
    await publicPage.getByRole('button',{name:'Send',exact:true}).click()
    await expect(publicPage.getByRole('status').filter({hasText:'Abena is preparing a reply'})).toHaveCount(0,{timeout:6000})
  }
  await ask()
  await expect(publicPage.getByText(approved,{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Submit for review',exact:true}).click()
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  await page.getByRole('button',{name:'Demo approver',exact:false}).click()
  await openSection(page,/^Abena answers/)
  await page.getByRole('button',{name:`Preview answer ${unique}`,exact:false}).click()
  await page.getByRole('button',{name:'Approve',exact:true}).click()
  await page.getByRole('button',{name:'Publish approved version',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'Published public version updated'})).toBeVisible()
  await ask()
  await expect(publicPage.getByText(approved,{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Unpublish',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'Public version withdrawn'})).toBeVisible()
  await ask()
  await expect(publicPage.getByText(approved,{exact:true})).toHaveCount(0)
  await publicPage.close()
})
